# --- English squadron <-> fleet ---
pat = re.compile(r"(?<![\w.$\-'])([Ff]leets?|[Ss]quadrons?)(?![\w(\-:'])")
SW = {'fleet': 'squadron', 'fleets': 'squadrons', 'Fleet': 'Squadron', 'Fleets': 'Squadrons',
      'squadron': 'fleet', 'squadrons': 'fleets', 'Squadron': 'Fleet', 'Squadrons': 'Fleets'}
def code_like(m):
    a, b = m.start(), m.end()
    after, before = s[b:b + 2], s[a - 4:a]
    if re.match(r'\.\w', after) or after.startswith(')') and before.endswith('of '):
        return True
    if s[a - 1] == ',' or s[a - 1] == '(':  # fight(n,fleets,where)
        return True
    if after.startswith(':['):  # fleets:[]
        return True
    return False
out, last, n = [], 0, 0
for m in pat.finditer(s):
    if code_like(m):
        continue
    out.append(s[last:m.start()]); out.append(SW[m.group(1)]); last = m.end(); n += 1
out.append(s[last:]); s = ''.join(out)
print('english swaps', n)

